# Scoring
# --------------------------------------------------------------------------


def parse_answer(completion: str, length: int, alphabet: str) -> str:
    """The word the model answered with.

    Prefers the last token of the target length, since a model that explains
    itself usually ends on its answer; falls back to the last alphabetic token.
    """
    tokens = [t for t in re.findall(r"[^\W\d_]+", completion.lower()) if set(t) <= set(alphabet)]
    if not tokens:
        return ""
    sized = [t for t in tokens if len(t) == length]
    return sized[-1] if sized else tokens[-1]


def is_consistent(answer: str, board: PinnedBoard) -> bool:
    """Whether ``answer`` fits the board and the excluded letters."""
    if len(answer) != len(board.board):
        return False
    return consistent_candidates(board.board, board.guessed, [answer]) == [answer]


@scorer(
    metrics={
        "exact": [mean(), stderr()],
        "consistent": [mean(), stderr()],
        "in_dictionary": [mean()],
    }
)
def probe_scorer(wordlist: str | None = None) -> Scorer:
    """Score a pinned-board answer: exact, consistent with the board, in the dictionary."""
    wordlist_path = str(resolve_wordlist(wordlist))

    async def score(state: TaskState, target: Target) -> Score:
        metadata: dict[str, Any] = state.metadata or {}
        board = PinnedBoard(
            word=str(metadata["word"]),
            board=str(metadata["board"]),
            excluded=str(metadata.get("excluded", "")),
        )
        alphabet = get_alphabet(Language(metadata.get("language", Language.ENGLISH.value)))
        answer = parse_answer(state.output.completion, len(board.word), alphabet)
        index = load_dictionary_index(wordlist_path)
        in_dictionary = answer in set(index.get(len(answer), []))
        exact = answer == board.word
        consistent = exact or is_consistent(answer, board)
        return Score(
            value={
                "exact": float(exact),
                "consistent": float(consistent),
                "in_dictionary": float(in_dictionary),
            },
            answer=answer,
            explanation=(
                f"board {board.render()} excluded [{', '.join(board.excluded)}] "
                f"target {board.word} answer {answer!r}"
            ),
            metadata={"raw_completion": state.output.completion},
        )

    return score


