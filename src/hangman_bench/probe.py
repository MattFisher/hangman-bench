TSV_FIELDS = ["word", "board", "excluded", "source", "zipf_band"]


def write_boards(boards: Sequence[PinnedBoard], path: pathlib.Path) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=TSV_FIELDS, delimiter="\t")
        writer.writeheader()
        for b in boards:
            writer.writerow(
                {
                    "word": b.word,
                    "board": b.board,
                    "excluded": b.excluded,
                    "source": b.source,
                    "zipf_band": b.zipf_band,
                }
            )


def read_boards(path: pathlib.Path) -> list[PinnedBoard]:
    """Read boards from a TSV; extra columns are ignored."""
    with path.open(newline="", encoding="utf-8") as handle:
        rows = csv.DictReader(handle, delimiter="\t")
        return [
            PinnedBoard(
                word=row["word"],
                board=row["board"],
                excluded=row.get("excluded", "") or "",
                source=row.get("source", "") or "",
                zipf_band=row.get("zipf_band", "") or "",
            )
            for row in rows
        ]


