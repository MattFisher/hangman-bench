def build_prompt(
    board: PinnedBoard,
    language: str = Language.ENGLISH.value,
    style: BoardStyle = "spaced",
    told_unique: bool = False,
) -> str:
    """The single prompt a board is shown as.

    ``told_unique`` adds the fact that exactly one word fits. In the game the
    model is never told this, so the default leaves it out; the flag exists to
    measure how much of the failure is not knowing the board is decisive.
    """
    excluded = ", ".join(board.excluded) if board.excluded else "none"
    ask = (
        "Exactly one word fits. Reply with that word only."
        if told_unique
        else "What is the word? Reply with the single most likely word only."
    )
    return (
        f"You are playing Hangman in {language}. "
        f"The board shows '_' for letters not yet revealed.\n"
        f"Board: {board.render(style)}\n"
        f"Letters already guessed that are not in the word: {excluded}\n"
        f"The word has {len(board.word)} letters. {ask}"
    )


@task
def pinned_probe(
    boards: str | None = None,
    source: str | None = None,
    n: int = 300,
    seed: int | None = 0,
    extra_wrong: int = 0,
    board_style: str = "spaced",
    told_unique: bool = False,
    language: str = Language.ENGLISH.value,
    wordlist: str | None = None,
) -> Task:
    """Name the word from a board that already determines it.

    Args:
        boards: TSV of boards (word, board, excluded, source, zipf_band), as
            written by analysis/pinned_boards.py. Generated from the
            dictionary when omitted.
        source: Keep only boards with this ``source`` value from the TSV
            (for example ``pilot`` or ``dictionary``).
        n: Boards to generate when no TSV is given.
        seed: Seed for generation. None draws a fresh seed and records it in
            every sample's metadata, so the run is reproducible afterwards
            without a canonical list to memorise.
        extra_wrong: Extra excluded letters added to generated boards.
        board_style: ``spaced`` (the game's rendering) or ``contiguous``.
        told_unique: Tell the model that exactly one word fits.
        language: Language of the words.
        wordlist: Dictionary for generation and scoring; defaults to the one
            shipped with the package.
    """
    if board_style not in ("spaced", "contiguous"):
        raise ValueError("board_style must be 'spaced' or 'contiguous'")
    style: BoardStyle = "spaced" if board_style == "spaced" else "contiguous"
    lang = Language(language.lower())
    wordlist_path = str(resolve_wordlist(wordlist))

    if boards is not None:
        items = read_boards(pathlib.Path(boards))
        if source is not None:
            items = [b for b in items if b.source == source]
        if not items:
            raise ValueError(
                f"No boards in {boards}" + (f" with source={source}" if source else "")
            )
        used_seed = None
    else:
        used_seed = seed if seed is not None else random.SystemRandom().randrange(2**32)
        index = load_dictionary_index(wordlist_path)
        items = sample_pinned_boards(index, n=n, seed=used_seed, extra_wrong=extra_wrong)

    samples = [
        Sample(
            id=f"{b.source or 'dictionary'}:{b.word}:{b.board}:{b.excluded}",
            input=build_prompt(b, lang.value, style, told_unique),
            target=b.word,
            metadata={
                "word": b.word,
                "board": b.board,
                "excluded": b.excluded,
                "source": b.source or "dictionary",
                "zipf_band": b.zipf_band,
                "length": len(b.word),
                "n_excluded": len(b.excluded),
                "revealed_fraction": round(b.revealed_fraction, 3),
                "board_style": style,
                "told_unique": told_unique,
                "seed": used_seed,
                "language": lang.value,
            },
        )
        for b in items
    ]
    return Task(
        dataset=MemoryDataset(samples),
        solver=generate(),
        scorer=probe_scorer(wordlist=wordlist),
    )
